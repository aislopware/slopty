/// `claude-haiku-4-5-20251001` -> `claude-haiku-4-5`.
fn snapshot_base(id: &str) -> Option<&str> {
    let (base, date) = id.rsplit_once('-')?;
    (date.len() == 8 && date.bytes().all(|b| b.is_ascii_digit())).then_some(base)
}

